"""Embed the protocol fixtures of the desktop app (DECKY-Agent: shared/fixtures/*.json)
into firmware/test/test_protocol/fixtures.h as raw string literals.

The app repository is read from a clone next to this one (../DECKY-Agent, or the older folder name
../PC-Control-Deck-Agent), or from
--agent DIR / the PCDECK_AGENT_DIR environment variable:

    python firmware/tools/gen_fixtures.py            # rewrite fixtures.h
    python firmware/tools/gen_fixtures.py --check    # fail if fixtures.h is out of date (CI)
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_AGENT = next((p for p in (ROOT.parent / "DECKY-Agent", ROOT.parent / "PC-Control-Deck-Agent") if p.is_dir()),
                     ROOT.parent / "DECKY-Agent")
OUT = ROOT / "firmware" / "test" / "test_protocol" / "fixtures.h"
AGENT_URL = "https://github.com/crazyramirez/DECKY-Agent"


def render(fix: Path) -> str:
    files = sorted(fix.glob("*.json"))
    if not files:
        raise SystemExit(f"no fixtures in {fix}: clone {AGENT_URL} next to this repository "
                         "or pass --agent DIR")
    lines = [
        "// GENERATED by firmware/tools/gen_fixtures.py from DECKY-Agent shared/fixtures/*.json - do not edit.",
        "#pragma once",
        "",
    ]
    for f in files:
        text = f.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
        if ')FX"' in text:
            raise SystemExit(f"{f.name} contains the raw-string delimiter")
        ident = "FX_" + f.stem.upper()
        lines.append(f'static const char {ident}[] = R"FX({text})FX";')
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--agent", type=Path, default=Path(os.environ.get("PCDECK_AGENT_DIR", DEFAULT_AGENT)),
                    help="DECKY-Agent checkout (default: ../DECKY-Agent)")
    ap.add_argument("--check", action="store_true", help="fail if fixtures.h is out of date")
    args = ap.parse_args()
    text = render(args.agent / "shared" / "fixtures")
    if args.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is out of date: run python firmware/tools/gen_fixtures.py", file=sys.stderr)
            return 1
        print("fixtures.h up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
