#!/usr/bin/env python3
"""
Embed the screensaver wallpapers of a deck: firmware/src/decks/<DECK>/assets/wallpapers.c / .h.

Sources: firmware/tools/wallpapers/<id>.jpg (1024x600, made for the JC1060P470C CryptoTracker with
gpt-image-2: dark, calm upper band for the clock) and wallpapers.json (id + Spanish / English
names). Each image is fitted to the deck's screen ("cover": scaled and centre-cropped) and stored
as a baseline JPEG; the firmware decodes it with JPEGDEC into RGB565 (full size for the
screensaver, 1/4 size for the thumbnails of the picker), so no thumbnails are stored. The screen
size comes from the deck's board_pins.h, the JPEG quality from tools/decks.py.

Usage (from the repository root):
    python firmware/tools/gen_wallpapers.py --deck JC4827W543     # or --deck all
Requires Pillow.
"""
import argparse
import io
import json
import os

from PIL import Image

import decks

FW = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(FW, "tools", "wallpapers")
# Set per deck by main(): output files, screen size, JPEG quality.
OUT_C = OUT_H = ""
W = H = QUALITY = 0


def fit(img):
    """Scale to cover W x H, centre crop."""
    s = max(W / img.width, H / img.height)
    img = img.resize((round(img.width * s), round(img.height * s)), Image.LANCZOS)
    x, y = (img.width - W) // 2, (img.height - H) // 2
    return img.crop((x, y, x + W, y + H))


def jpeg_for_deck(path):
    raw = open(path, "rb").read()
    img = Image.open(io.BytesIO(raw))
    if img.size == (W, H) and not img.info.get("progressive") and img.mode == "RGB":
        return raw  # already the right size and baseline: keep the original stream
    buf = io.BytesIO()
    fit(img.convert("RGB")).save(buf, "JPEG", quality=QUALITY, optimize=True, progressive=False, subsampling=2)
    return buf.getvalue()


def c_bytes(data, per_line=32):
    return "\n".join(
        "    " + ",".join("0x%02x" % b for b in data[i : i + per_line]) + "," for i in range(0, len(data), per_line)
    )


def build(deck):
    global OUT_C, OUT_H, W, H, QUALITY
    OUT_C = os.path.join(decks.deck_dir(deck), "assets", "wallpapers.c")
    OUT_H = os.path.join(decks.deck_dir(deck), "assets", "wallpapers.h")
    W, H = decks.screen(deck)
    QUALITY = decks.TOOLS[deck]["wallpaper_quality"]
    meta = json.load(open(os.path.join(SRC, "wallpapers.json"), encoding="utf-8"))
    c = [
        "/* Generated by firmware/tools/gen_wallpapers.py - do not edit.",
        " * Wallpapers made with OpenAI gpt-image-2 for the JC1060P470C CryptoTracker. */",
        '#include "wallpapers.h"',
        "",
    ]
    rows, total = [], 0
    for w in meta:
        data = jpeg_for_deck(os.path.join(SRC, w["id"] + ".jpg"))
        total += len(data)
        c.append("static const uint8_t wp_%s_jpg[] __attribute__((aligned(4))) = {\n%s\n};\n" % (w["id"], c_bytes(data)))
        rows.append('    {"%s", "%s", "%s", wp_%s_jpg, sizeof(wp_%s_jpg)},' % (w["id"], w["name_es"], w["name_en"], w["id"], w["id"]))
        print("%-8s %6d bytes" % (w["id"], len(data)))
    c.append("const wallpaper_info_t WALLPAPERS[] = {")
    c += rows
    c.append("};")
    c.append("const int WALLPAPER_COUNT = sizeof(WALLPAPERS) / sizeof(WALLPAPERS[0]);")
    os.makedirs(os.path.dirname(OUT_C), exist_ok=True)
    with open(OUT_C, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(c) + "\n")
    h = """/* Generated by firmware/tools/gen_wallpapers.py - do not edit */
#pragma once
#include <stdint.h>

#ifdef __cplusplus
extern "C" {
#endif

typedef struct {
    const char *id;       /* stable id (stored in the settings by index, shown nowhere) */
    const char *name_es;
    const char *name_en;
    const uint8_t *jpg;   /* baseline JPEG, WALLPAPER_W x WALLPAPER_H */
    uint32_t jpg_size;
} wallpaper_info_t;

extern const wallpaper_info_t WALLPAPERS[];
extern const int WALLPAPER_COUNT;

#define WALLPAPER_W %d
#define WALLPAPER_H %d

#ifdef __cplusplus
}
#endif
""" % (W, H)
    with open(OUT_H, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(h)
    print("done: %d wallpapers, %d KB of JPEG -> %s" % (len(meta), total // 1024, os.path.relpath(OUT_C, FW)))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--deck", default="all", help="deck key (src/decks/<KEY>) or all")
    for deck in decks.selected(ap.parse_args().deck):
        build(deck)


if __name__ == "__main__":
    main()
