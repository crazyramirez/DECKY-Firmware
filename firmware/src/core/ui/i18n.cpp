void set_lang(storage::Lang lang) { s_lang = lang; }
storage::Lang lang() { return s_lang; }

const char *tr(Str id) {
  const auto i = static_cast<size_t>(id);
  if (i >= static_cast<size_t>(Str::Count)) return "?";
  const bool en = s_lang == storage::Lang::En;
  if (const char *own = deck_tr(id, en)) return own;
  return en ? kTable[i].en : kTable[i].es;
}

